import { defineConfig, Plugin } from 'vite'
import path from 'path'
import fs from 'fs'
import tailwindcss from '@tailwindcss/vite'
import react from '@vitejs/plugin-react'

function singleFileBundlePlugin(): Plugin {
  return {
    name: 'single-file-bundle',
    enforce: 'post',
    generateBundle(_, bundle) {
      let htmlFileName = ''
      let htmlSource = ''
      const cssChunks: string[] = []
      const jsChunks: string[] = []

      for (const [fileName, chunk] of Object.entries(bundle)) {
        if (fileName.endsWith('.html') && chunk.type === 'asset') {
          htmlFileName = fileName
          htmlSource = typeof chunk.source === 'string' ? chunk.source : Buffer.from(chunk.source).toString('utf-8')
        } else if (fileName.endsWith('.css') && chunk.type === 'asset') {
          const css = typeof chunk.source === 'string' ? chunk.source : Buffer.from(chunk.source).toString('utf-8')
          cssChunks.push(css)
        } else if (fileName.endsWith('.js') && chunk.type === 'chunk') {
          jsChunks.push(chunk.code)
        }
      }

      if (htmlFileName && htmlSource) {
        // Remove external script and stylesheet tags generated by Vite
        let inlinedHtml = htmlSource
          .replace(/<script[^>]*src="[^"]*"[^>]*><\/script>/gi, '')
          .replace(/<link[^>]*rel="stylesheet"[^>]*href="[^"]*"[^>]*>/gi, '')
          .replace(/<link[^>]*href="\/manifest\.json"[^>]*>/gi, '')

        const styleTag = cssChunks.length > 0 ? `<style>\n${cssChunks.join('\n')}\n</style>` : ''
        // Escape HTML5 raw-text script sequences (<!--, <script, </script) inside JS string literals
        // so the browser HTML parser never enters script-data-double-escaped state
        const safeJs = jsChunks
          .join('\n')
          .replace(/<!--/g, '<\\!--')
          .replace(/<script/gi, '<\\x73cript')
          .replace(/<\/script/gi, '<\\/script')
        const scriptTag = `<script type="module">\n${safeJs}\n</script>`

        inlinedHtml = inlinedHtml.replace('</head>', () => `${styleTag}\n</head>`)
        inlinedHtml = inlinedHtml.replace('</body>', () => `${scriptTag}\n</body>`)

        const htmlAsset = bundle[htmlFileName]
        if (htmlAsset && htmlAsset.type === 'asset') {
          htmlAsset.source = inlinedHtml
        }

        // Also write a standalone copy in the project root for easy double-clicking or sharing
        try {
          fs.writeFileSync(path.resolve(__dirname, './TATU_FAZ_App.html'), inlinedHtml, 'utf-8')
        } catch {}
      }
    },
  }
}

export default defineConfig({
  base: './',
  server: {
    host: '0.0.0.0',
    port: 5173,
    allowedHosts: true,
  },
  preview: {
    host: '0.0.0.0',
    port: 5173,
    allowedHosts: true,
  },
  build: {
    assetsInlineLimit: 10000000, // Inline all Figma PNG assets as base64 Data URLs
    cssCodeSplit: false,
    rollupOptions: {
      output: {
        inlineDynamicImports: true,
      },
    },
  },
  plugins: [
    // The React and Tailwind plugins are both required for Make, even if
    // Tailwind is not being actively used – do not remove them
    react(),
    tailwindcss(),
    singleFileBundlePlugin(),
  ],
  resolve: {
    alias: [
      {
        find: /^figma:asset\/(.*)$/,
        replacement: path.resolve(__dirname, './assets/$1'),
      },
      {
        find: /^(@?[^@/]+(?:\/[^@/]+)?)@\d+\.\d+\.\d+(.*)?$/,
        replacement: '$1$2',
      },
      {
        find: '@',
        replacement: path.resolve(__dirname, './src/app'),
      },
    ],
  },
})
